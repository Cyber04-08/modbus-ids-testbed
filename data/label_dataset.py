"""
Label a raw capture into the ground-truth dataset (Phase 2 output).

Reads the passive capture (data/capture.csv) and the scenario's ground-truth
manifest (data/attack_manifest.json), and writes data/labeled.csv with two
added columns:

    label        - "benign" | "replay" | "injection"   (scored requests)
                   "replay_seed"                       (request, not scored)
                   "response"                          (PLC reply, not scored)
    is_attack    - 1 | 0 for scored requests, blank for everything not scored

How each frame is labeled:
  * Responses are generated by the PLC, never by a client, so they cannot be
    malicious requests. They are labeled "response" and left unscored, even
    on an attacker's connection.
  * Requests on the operator's connection are benign.
  * Requests on an attack connection are matched, in order and by exact
    bytes, to the per-packet log the attack script wrote (in the manifest).
    A logged "attack" packet takes the attack's label; the replay's "seed"
    packet (its stand-in for the recorded operator command, which is not
    itself a replay) is labeled "replay_seed" and left unscored.
  * Cross-checks, reported rather than silently trusted: every logged packet
    must match exactly one captured request, and every attack request must
    fall inside its attack's recorded wall-clock window.

Uses only the standard library (csv/json) so it runs with no extra installs.

Usage:
    python data/label_dataset.py
"""

import csv
import json
from pathlib import Path

DATA_DIR = Path(__file__).resolve().parent
CAPTURE_CSV = DATA_DIR / "capture.csv"
MANIFEST = DATA_DIR / "attack_manifest.json"
LABELED_CSV = DATA_DIR / "labeled.csv"

LABELS = ("benign", "replay", "injection", "replay_seed", "response", "unknown", "unmatched")


def main() -> None:
    if not CAPTURE_CSV.exists():
        raise SystemExit(f"No capture at {CAPTURE_CSV} - run attacks/run_scenario.py first.")
    if not MANIFEST.exists():
        raise SystemExit(f"No manifest at {MANIFEST} - run attacks/run_scenario.py first.")

    manifest = json.loads(MANIFEST.read_text())
    # JSON object keys are strings; normalize to int ports.
    port_roles = {int(p): role for p, role in manifest["source_port_roles"].items()}
    windows = {w["type"]: w for w in manifest.get("attack_windows", [])}
    # Per attack connection: the queue of packets its script logged, in send order.
    pending = {w["source_port"]: list(w.get("packets", [])) for w in windows.values()}
    logged_total = sum(len(q) for q in pending.values())

    counts = {k: 0 for k in LABELS}
    window_mismatches = 0
    total = 0

    with open(CAPTURE_CSV, newline="") as fin, open(LABELED_CSV, "w", newline="") as fout:
        reader = csv.DictReader(fin)
        fieldnames = reader.fieldnames + ["label", "is_attack"]
        writer = csv.DictWriter(fout, fieldnames=fieldnames)
        writer.writeheader()

        for row in reader:
            total += 1
            try:
                port = int(row["client_port"])
            except (KeyError, ValueError):
                port = -1
            role = port_roles.get(port, "unknown")

            if row["direction"] == "resp":
                label, is_attack = "response", ""
            elif role in ("benign", "unknown"):
                label, is_attack = role, (0 if role == "benign" else "")
            else:
                queue = pending.get(port, [])
                if queue and queue[0]["raw_hex"] == row["raw_hex"]:
                    rec = queue.pop(0)
                    if rec["kind"] == "seed":
                        label, is_attack = "replay_seed", ""
                    else:
                        label, is_attack = role, 1
                else:
                    label, is_attack = "unmatched", ""

                w = windows.get(role)
                try:
                    t = float(row["wall_time"])
                except (KeyError, ValueError):
                    t = None
                if w and t is not None and not (w["start"] - 1 <= t <= w["end"] + 1):
                    window_mismatches += 1

            row["label"], row["is_attack"] = label, is_attack
            counts[label] += 1
            writer.writerow(row)

    leftover = sum(len(q) for q in pending.values())
    print(f"Labeled {total} frames -> {LABELED_CSV}")
    for k in LABELS:
        if counts[k] or k in ("benign", "replay", "injection"):
            print(f"  {k:12s}: {counts[k]}")
    print(f"  scored requests: {counts['benign'] + counts['replay'] + counts['injection']} "
          f"({counts['replay'] + counts['injection']} attack); responses and the "
          "replay seed are kept but not scored")
    print(f"  packet-log match: {logged_total - leftover}/{logged_total} logged attack-script "
          "packets matched to captured requests by exact bytes")
    if leftover or counts["unmatched"]:
        print(f"  WARNING: {leftover} logged packets not captured, {counts['unmatched']} "
              "captured attack-connection requests not in the log - investigate.")
    if counts["unknown"]:
        print(f"  NOTE: {counts['unknown']} frames from unrecognized source ports "
              "(unexpected client) - left unlabeled.")
    if window_mismatches:
        print(f"  WARNING: {window_mismatches} attack-connection frames fell outside their "
              "recorded time window - investigate.")
    else:
        print("  Cross-check OK: all attack-connection frames fall within their recorded windows.")


if __name__ == "__main__":
    main()
